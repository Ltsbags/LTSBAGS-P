export function getTranslation(
  langCode: string,
  key: string,
  customMap?: LanguageTranslationsMap
): string {
  const activeCode = langCode.toLowerCase();
  
  // 1. Check custom override map if provided
  if (customMap && customMap[activeCode] && customMap[activeCode][key]) {
    return customMap[activeCode][key];
  }

  // 2. Check initial translations map for specified language
  if (INITIAL_TRANSLATIONS_MAP[activeCode] && INITIAL_TRANSLATIONS_MAP[activeCode][key]) {
    return INITIAL_TRANSLATIONS_MAP[activeCode][key];
  }

  // 3. Fallback to default English translation
  if (DEFAULT_TRANSLATIONS[key]) {
    return DEFAULT_TRANSLATIONS[key];
  }

  // 4. Fallback formatted key string if not found anywhere
  const keyParts = key.split('.');
  const lastPart = keyParts[keyParts.length - 1];
  return lastPart.replace(/([A-Z])/g, ' $1').replace(/^./, (str) => str.toUpperCase());
}
